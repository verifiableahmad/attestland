#!/usr/bin/env python3
"""Physical position of each GPU node -> scheduler topology (ADR 007).

Input: a JSON object {node: that instance's entry from EC2
DescribeInstanceTopology, or "" when there is none}. An entry carries
"NetworkNodes", the network nodes above the instance from the top layer down to
the one it attaches to; the last two (without the "nn-" prefix) become block
and sub-block. EC2 reports
topology only for some instance types (larger GPU and HPC types, not
g6.2xlarge); a node without an entry becomes "unknown", which puts every such
node in one group: no data means no distance to optimise.

    topology.py labels  --facts facts.json   # node -> {label: value}, JSON
    topology.py kubectl --facts facts.json   # the `kubectl label` commands for those labels
    topology.py slurm   --facts facts.json   # topology.conf for topology/tree

The labels feed Kueue's Topology (sched/k8s/kueue/topology.yaml), whose levels
are block, sub-block, then kubernetes.io/hostname.
"""

from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

LABEL_BLOCK = "fleet.attestland/topology-block"
LABEL_SUBBLOCK = "fleet.attestland/topology-subblock"
UNKNOWN = "unknown"


def _value(v: object) -> str:
    """A valid Kubernetes label value (<= 63 chars of [A-Za-z0-9_.-]), or UNKNOWN."""
    s = re.sub(r"[^A-Za-z0-9_.-]", "-", str(v or "")).strip("-_.")[:63].strip("-_.")
    return s or UNKNOWN


def position(raw: str | dict | None) -> tuple[str, str]:
    """(block, sub-block) from one DescribeInstanceTopology entry."""
    if isinstance(raw, str):
        try:
            raw = json.loads(raw) if raw.strip() else None
        except json.JSONDecodeError:
            raw = None
    if not isinstance(raw, dict):
        return UNKNOWN, UNKNOWN
    nodes = raw.get("NetworkNodes")
    if not isinstance(nodes, list) or len(nodes) < 2:
        return UNKNOWN, UNKNOWN
    return tuple(_value(str(n).removeprefix("nn-")) for n in nodes[-2:])


def labels(facts: dict) -> dict[str, dict[str, str]]:
    out = {}
    for node in sorted(facts):
        block, sub = position(facts[node])
        out[node] = {LABEL_BLOCK: block, LABEL_SUBBLOCK: sub}
    return out


def kubectl_commands(facts: dict) -> str:
    return "".join(
        shlex.join(["kubectl", "label", "node", node, "--overwrite", *(f"{k}={v}" for k, v in sorted(lab.items()))]) + "\n"
        for node, lab in labels(facts).items())


def slurm_conf(facts: dict) -> str:
    """topology/tree: one leaf switch per sub-block, one switch per block, a root if needed."""
    tree: dict[str, dict[str, list[str]]] = {}
    for node in sorted(facts):
        block, sub = position(facts[node])
        tree.setdefault(block, {}).setdefault(sub, []).append(node)
    lines = ["# Generated by fleet/topology/topology.py from EC2 instance topology. Do not edit."]
    blocks = []
    for block in sorted(tree):
        b = f"b-{block[:8]}"
        subs = []
        for sub in sorted(tree[block]):
            s = f"s-{block[:8]}-{sub[:8]}"
            lines.append(f"SwitchName={s} Nodes={','.join(tree[block][sub])}")
            subs.append(s)
        lines.append(f"SwitchName={b} Switches={','.join(subs)}")
        blocks.append(b)
    if len(blocks) > 1:
        lines.append(f"SwitchName=root Switches={','.join(blocks)}")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("output", choices=["labels", "kubectl", "slurm"])
    ap.add_argument("--facts", type=Path, required=True)
    a = ap.parse_args(argv)
    facts = json.loads(a.facts.read_text())
    if a.output == "labels":
        print(json.dumps(labels(facts), indent=2, sort_keys=True))
    elif a.output == "kubectl":
        sys.stdout.write(kubectl_commands(facts))
    else:
        sys.stdout.write(slurm_conf(facts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
