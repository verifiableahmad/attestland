"""SONiC renderer (docker-sonic-vs): the lab's default NOS (ADR 012).

Each switch gets a setup.sh, run once at deploy through containerlab `exec`,
and a frr.conf it applies with `vtysh -f`. setup.sh does the SONiC side with
the click CLI (`config ...`, which writes CONFIG_DB): addresses, VLANs, the
VTEP, VLAN-VNI and VRF-VNI maps. SONiC's routing stack is FRR, so the BGP and
BFD sections are gen_frr's, with SONiC's VRF names.

Order follows the SONiC EVPN HLD: VLAN before its VNI map, the L3 VNI's VLAN
map before the VRF-VNI map, and the VRF in the kernel before FRR binds the VNI.
The tenant gateway is the same address on every leaf; production SONiC would
add a static anycast gateway MAC, which this lab does not configure.
"""

from __future__ import annotations

from ipaddress import ip_interface
from pathlib import Path

import fabric
import gen_frr

READY = "/tmp/al-ready"          # setup.sh writes it last; the lab tests wait for it


def sonic_port(port: str) -> str:
    """eth1 -> Ethernet0, eth2 -> Ethernet4: docker-sonic-vs maps each ethN to a 4-lane port."""
    return f"Ethernet{4 * (int(port.removeprefix('eth')) - 1)}"


def vrf_name(t: fabric.Tenant) -> str:
    return f"Vrf-{t.name}"       # SONiC requires the Vrf prefix


def l2_vlan(t: fabric.Tenant) -> int:
    return t.l2_evi              # 10, 20


def l3_vlan(t: fabric.Tenant) -> int:
    return t.l3_evi              # 101, 201: the VLAN that carries the L3 VNI


def _head(name: str, what: str, ports: list[str]) -> list[str]:
    sh = ["#!/bin/bash", f"# Generated by gen.py from fabric.py: {name}, {what}.", "set -euo pipefail",
          "# Front-panel ports appear once syncd is up; then let the switch settle."]
    sh += [f"until ip link show {sonic_port(p)} >/dev/null 2>&1; do sleep 1; done" for p in ports]
    sh += ["sleep 5",
           "sysctl -qw net.ipv4.fib_multipath_hash_policy=1   # ECMP on the L4 hash, as on hardware"]
    return sh


def _routed(loopback: str, ifaces: dict[str, str]) -> list[str]:
    sh = ["config loopback add Loopback0", f"config interface ip add Loopback0 {loopback}"]
    for port, addr in ifaces.items():
        sh += [f"config interface ip add {sonic_port(port)} {addr}",
               f"config interface startup {sonic_port(port)}"]
    return sh


def _tenant(t: fabric.Tenant) -> list[str]:
    acc, vrf = sonic_port(f"eth{t.host_port}"), vrf_name(t)
    l2, l3 = l2_vlan(t), l3_vlan(t)
    return [f"# tenant {t.name}: L2 VNI {t.l2_vni} on Vlan{l2}, L3 VNI {t.l3_vni} on Vlan{l3}",
            f"config vrf add {vrf}",
            f"config vlan add {l2}",
            f"config vlan member add -u {l2} {acc}",
            f"config interface startup {acc}",
            f"config vxlan map add vtep1 {l2} {t.l2_vni}",
            f"config neigh-suppress vlan {l2} on",
            f"config vlan add {l3}",
            f"config vxlan map add vtep1 {l3} {t.l3_vni}",
            f"config vrf add_vrf_vni_map {vrf} {t.l3_vni}",
            f"config interface vrf bind Vlan{l2} {vrf}",
            f"config interface ip add Vlan{l2} {t.gateway}",
            f"config interface vrf bind Vlan{l3} {vrf}"]


def _tail(vrfs: list[str]) -> list[str]:
    sh = ["# FRR binds an L3 VNI only to a VRF the kernel already has."]
    sh += [f"until ip link show {v} >/dev/null 2>&1; do sleep 1; done" for v in vrfs]
    sh += ["# docker-sonic-vs leaves bgpd stopped and has no bfdd program (it is",
           "# frr_mgmt_framework-only), so start bgpd and run bfdd directly.",
           "supervisorctl status bgpd | grep -q RUNNING || supervisorctl start bgpd",
           "pgrep -x bfdd >/dev/null || /usr/lib/frr/bfdd -d -A 127.0.0.1",
           "until vtysh -c 'show bfd peers' >/dev/null 2>&1; do sleep 1; done",
           "vtysh -f /configs/frr.conf",
           f"touch {READY}"]
    return sh


def render_spine(node: fabric.Node) -> tuple[str, str]:
    sh = _head(node.name, f"spine, AS {node.asn}, EVPN transit", list(node.ifaces))
    sh += _routed(node.loopback, node.ifaces) + _tail([])
    return "\n".join(sh) + "\n", "\n".join(gen_frr.spine_bgp(node)) + "\n"


def render_leaf(node: fabric.Node) -> tuple[str, str]:
    lo = node.loopback.split("/")[0]
    ports = sorted(set(node.ifaces) | {f"eth{t.host_port}" for t in fabric.TENANTS},
                   key=lambda p: int(p[3:]))
    sh = _head(node.name, f"leaf, AS {node.asn}, VTEP {lo}", ports)
    sh += _routed(node.loopback, node.ifaces)
    sh += [f"config vxlan add vtep1 {lo}", "config vxlan evpn_nvo add nvo1 vtep1"]
    for t in fabric.TENANTS:
        sh += _tenant(t)
    sh += _tail([vrf_name(t) for t in fabric.TENANTS])
    return "\n".join(sh) + "\n", "\n".join(gen_frr.leaf_bgp(node, vrf=vrf_name)) + "\n"


def _node(name: str, image_kind: str, cfg_dir: str, labels: str) -> list[str]:
    return [f"    {name}:", f"      kind: {image_kind}", f"      labels: {{{labels}}}",
            "      binds:", f"        - {cfg_dir}:/configs:ro",
            "      exec:", "        - bash /configs/setup.sh"]


def render_topology(fab: fabric.Fabric, v: dict[str, str]) -> str:
    out = ["# Generated by gen.py from fabric.py (SONiC). Do not edit by hand.",
           "name: al-fabric",
           "mgmt:", "  network: al-fabric-mgmt", "  ipv4-subnet: 172.30.30.0/24",
           "topology:", "  kinds:",
           "    sonic-vs:", f"      image: {v['SONIC_VS_IMAGE']}",
           "    linux:", f"      image: {v['LAB_HOST_IMAGE']}",
           "  nodes:"]
    for n in fab.spines + fab.leaves:
        out += _node(n.name, "sonic-vs", f"configs/sonic/{n.name}", f"role: {n.role}, nos: sonic")
    for h in fab.hosts:
        gw = h.tenant.gateway.split("/")[0]
        out += [f"    {h.name}:", "      kind: linux",
                f"      labels: {{role: host, tenant: {h.tenant.name}, leaf: {h.leaf}}}",
                "      exec:", "        - ip link set eth1 mtu 1450",
                f"        - ip addr add {h.address} dev eth1",
                f"        - ip route add 172.16.0.0/16 via {gw} dev eth1"]
    out.append("  links:")
    for a, b in fab.links:
        out.append(f"    - endpoints: [\"{a}\", \"{b}\"]")
    return "\n".join(out) + "\n"


def render_rail(v: dict[str, str]) -> tuple[dict[str, tuple[str, str]], str]:
    """Rail-optimised pure-L3 backend: leaves advertise their GPU-facing /31s."""
    r = fabric.rail_build()
    cfgs = {}
    for sp in r["spines"]:
        sh = _head(sp["name"], f"rail spine, AS {sp['asn']}", list(sp["ifaces"]))
        sh += _routed(sp["loopback"], sp["ifaces"]) + _tail([])
        frr = gen_frr.BFD_PROFILE + gen_frr.bgp_head(sp["asn"], sp["loopback"], sp["neighbors"], "RAILS")
        cfgs[sp["name"]] = ("\n".join(sh) + "\n", "\n".join(frr + ["exit", "!"]) + "\n")
    for lf in r["leaves"]:
        gpu_nets = [str(ip_interface(a).network)
                    for p, a in lf["ifaces"].items() if int(p[3:]) < fabric.UPLINK_PORT_BASE]
        sh = _head(lf["name"], f"rail leaf, AS {lf['asn']}, pure L3", sorted(lf["ifaces"], key=lambda p: int(p[3:])))
        sh += _routed(lf["loopback"], lf["ifaces"]) + _tail([])
        frr = gen_frr.BFD_PROFILE + gen_frr.bgp_head(lf["asn"], lf["loopback"], lf["neighbors"],
                                                     "SPINES", gpu_nets)
        cfgs[lf["name"]] = ("\n".join(sh) + "\n", "\n".join(frr + ["exit", "!"]) + "\n")
    topo = ["# Generated by gen.py: rail-optimised pure-L3 backend (SONiC, stretch).",
            "name: al-rail",
            "mgmt:", "  network: al-rail-mgmt", "  ipv4-subnet: 172.30.31.0/24",
            "topology:", "  kinds:",
            "    sonic-vs:", f"      image: {v['SONIC_VS_IMAGE']}",
            "    linux:", f"      image: {v['LAB_HOST_IMAGE']}",
            "  nodes:"]
    for n in r["spines"] + r["leaves"]:
        role = "spine" if n in r["spines"] else "leaf"
        topo += _node(n["name"], "sonic-vs", f"configs/sonic-rail/{n['name']}", f"role: {role}, nos: sonic")
    for node in r["nodes"]:
        topo += [f"    {node['name']}:", "      kind: linux", "      exec:"]
        for nic in node["nics"]:
            topo += [f"        - ip addr add {nic['address']} dev {nic['iface']}",
                     f"        - ip route add 10.12.0.0/16 via {nic['gateway']} dev {nic['iface']} metric {nic['rail']}"]
    topo.append("  links:")
    for a, b in r["links"]:
        topo.append(f"    - endpoints: [\"{a}\", \"{b}\"]")
    return cfgs, "\n".join(topo) + "\n"


def _write(d: Path, setup: str, frr: str) -> None:
    d.mkdir(parents=True, exist_ok=True)
    (d / "setup.sh").write_text(setup)
    (d / "frr.conf").write_text(frr)


def write_all(out_dir: Path, here: Path, v: dict[str, str]) -> tuple[int, int]:
    fab = fabric.build()
    for n in fab.spines:
        _write(out_dir / "sonic" / n.name, *render_spine(n))
    for n in fab.leaves:
        _write(out_dir / "sonic" / n.name, *render_leaf(n))
    (here / "fabric.clab.yml").write_text(render_topology(fab, v))
    rail_cfgs, rail_topo = render_rail(v)
    for name, (setup, frr) in rail_cfgs.items():
        _write(out_dir / "sonic-rail" / name, setup, frr)
    (here / "rail.clab.yml").write_text(rail_topo)
    return len(fab.spines) + len(fab.leaves), len(rail_cfgs)
